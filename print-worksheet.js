/**
 * EduSim Virtual Lab — Print/Export PDF Worksheet
 * Generates a clean A4-friendly printable view of the circuit,
 * component list, and a student notes area.
 */
'use strict';

document.addEventListener('DOMContentLoaded', () => {
  const printBtn = document.getElementById('printWorksheetBtn');
  const printContainer = document.getElementById('printContainer');
  const svgCanvas = document.getElementById('labSvg');

  if (!printBtn || !printContainer || !svgCanvas) return;

  printBtn.addEventListener('click', generateAndPrintWorksheet);

  function generateAndPrintWorksheet() {
    // 1. Get project info
    const projectName = document.getElementById('labProjectName')?.textContent || 'Untitled Lab';
    const currentDate = new Date().toLocaleDateString();

    // 2. Clone the SVG and adjust viewBox to fit the circuit
    const svgClone = cloneAndAdjustSVG(svgCanvas);

    // 3. Generate component list
    const compTable = generateComponentTable();

    // 4. Construct the Print Layout
    printContainer.innerHTML = `
      <div class="print-header">
        <div class="print-brand">EduSim Virtual Lab</div>
        <div class="print-student-info">
          <div>Name: ____________________________________</div>
          <div>Date: ${currentDate}</div>
        </div>
      </div>

      <h1 class="print-title">${projectName}</h1>

      <div class="print-section">
        <h2 class="print-section-title">Circuit Diagram</h2>
        <div class="print-svg-wrapper">
          ${svgClone.outerHTML}
        </div>
      </div>

      <div class="print-section">
        <h2 class="print-section-title">Component List</h2>
        ${compTable}
      </div>

      <div class="print-section" style="flex: 1;">
        <h2 class="print-section-title">Student Notes & Observations</h2>
        <div class="print-notes-area"></div>
      </div>

      <div class="print-footer">
        Generated by EduSim Virtual Lab — mark ai
      </div>
    `;

    // 5. Trigger print
    window.print();
  }

  function cloneAndAdjustSVG(originalSvg) {
    const clone = originalSvg.cloneNode(true);
    clone.removeAttribute('id');
    clone.classList.remove('lab-canvas');
    clone.classList.add('print-svg');

    // Remove active wire from print
    const activeWire = clone.querySelector('#activeWire');
    if (activeWire) activeWire.remove();

    // Reset transformations to avoid panning/zooming offsets in print
    const wiresLayer = clone.querySelector('#wiresLayer');
    const componentsLayer = clone.querySelector('#componentsLayer');
    if (wiresLayer) wiresLayer.removeAttribute('transform');
    if (componentsLayer) componentsLayer.removeAttribute('transform');

    // Remove selection indicators
    clone.querySelectorAll('.selected').forEach(el => el.classList.remove('selected'));
    
    // Hide pin hit circles to make diagram cleaner (or change their stroke)
    clone.querySelectorAll('.pin-circle').forEach(el => el.style.display = 'none');

    // Calculate bounding box of all components and wires
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    
    // Iterate over components from the global `components` array
    if (window.components && window.components.length > 0) {
      window.components.forEach(comp => {
        // Approximate bounding box
        const cx = comp.x;
        const cy = comp.y;
        const cw = comp.def.w || 50;
        const ch = comp.def.h || 50;
        
        if (cx < minX) minX = cx;
        if (cy < minY) minY = cy;
        if (cx + cw > maxX) maxX = cx + cw;
        if (cy + ch > maxY) maxY = cy + ch;
      });
    }

    // Add padding
    const padding = 20;
    if (minX !== Infinity) {
      minX -= padding;
      minY -= padding;
      maxX += padding;
      maxY += padding;
      const width = maxX - minX;
      const height = maxY - minY;
      clone.setAttribute('viewBox', `${minX} ${minY} ${width} ${height}`);
    } else {
      // Fallback if no components
      clone.setAttribute('viewBox', '0 0 800 600');
    }

    // Ensure colors are print-friendly (e.g., wires)
    clone.querySelectorAll('.lab-wire').forEach(wire => {
      // Force black or dark gray wires for B&W printing
      wire.setAttribute('stroke', '#333333');
    });

    return clone;
  }

  function generateComponentTable() {
    if (!window.components || window.components.length === 0) {
      return '<p class="print-empty">No components in the circuit.</p>';
    }

    // Tally components by type/label
    const tally = {};
    window.components.forEach(c => {
      const name = c.props.label || c.def.label;
      if (!tally[name]) {
        tally[name] = { count: 0, desc: c.def.desc || '' };
      }
      tally[name].count++;
    });

    let rows = '';
    Object.keys(tally).sort().forEach(name => {
      rows += `
        <tr>
          <td style="text-align: center; width: 60px;">${tally[name].count}</td>
          <td style="font-weight: bold;">${name}</td>
          <td>${tally[name].desc}</td>
        </tr>
      `;
    });

    return `
      <table class="print-table">
        <thead>
          <tr>
            <th>Qty</th>
            <th>Component</th>
            <th>Description</th>
          </tr>
        </thead>
        <tbody>
          ${rows}
        </tbody>
      </table>
    `;
  }
});
